package com.motionloop.app.feature.settings

import androidx.compose.foundation.layout.Column
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.ui.platform.LocalContext
import com.motionloop.app.domain.model.DemoPhotos
import com.motionloop.app.ui.components.MenuRow
import com.motionloop.app.ui.components.SectionTitle
import com.motionloop.app.ui.components.SimpleScreen
import com.motionloop.app.ui.theme.MlColors

private data class License(val name: String, val license: String, val url: String)

private val libraries = listOf(
    License("AndroidX and Jetpack Compose", "Apache License 2.0", "https://developer.android.com/jetpack/androidx"),
    License("Kotlin and kotlinx (coroutines, serialization)", "Apache License 2.0", "https://kotlinlang.org"),
    License("Dagger and Hilt", "Apache License 2.0", "https://dagger.dev"),
    License("MediaPipe Tasks Vision and the magic_touch model", "Apache License 2.0", "https://ai.google.dev/edge/mediapipe"),
    License("LiteRT (TensorFlow Lite)", "Apache License 2.0", "https://ai.google.dev/edge/litert"),
    License("MiDaS v2.1 small depth model", "MIT License", "https://github.com/isl-org/MiDaS"),
    License("ML Kit Subject Segmentation", "ML Kit terms of service", "https://developers.google.com/ml-kit/terms"),
)

@Composable
fun LicensesScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    SimpleScreen("Licenses and credits", onBack) {
        SectionTitle("Open source")
        libraries.forEach { lib ->
            MenuRow(lib.name, subtitle = lib.license, onClick = { openUrl(context, lib.url) })
        }
        SectionTitle("Sample photos")
        Text(
            "All sample photos are released under CC0 (public domain dedication) and come from Wikimedia Commons. " +
                "Credit is not required, but here are the photographers.",
            style = MaterialTheme.typography.bodySmall,
            color = MlColors.TextSecondary,
        )
        Column {
            DemoPhotos.all.forEach { photo ->
                MenuRow(photo.title, subtitle = "Photo by ${photo.author}, CC0", onClick = { openUrl(context, photo.sourceUrl) })
            }
        }
        SectionTitle("Sounds and skies")
        Text(
            "Built-in skies, particles, light leaks and ambient sounds are generated by MotionLoop's own code.",
            style = MaterialTheme.typography.bodySmall,
            color = MlColors.TextSecondary,
        )
    }
}
